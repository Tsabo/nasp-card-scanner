/**
 * @file Builds the site into `_site/`, ready for GitHub Pages:
 *
 *   _site/
 *     index.html, manifest.webmanifest, css/, assets/   copied as they are
 *     js/                                              the app, compiled from src/
 *     sw.js                                            the service worker, compiled
 *                                                      from service-worker/, with the
 *                                                      file list and version filled in
 *
 * Run with `npm run build`. `npm start` builds and then serves the result.
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const OUTPUT = join(ROOT, "_site");

/** Files and folders copied into the site unchanged. */
const STATIC_FILES = ["index.html", "manifest.webmanifest", "css", "assets"];

build();

function build(): void {
  rmSync(OUTPUT, { recursive: true, force: true });

  console.log("Compiling the app…");
  compile("tsconfig.json");
  console.log("Compiling the service worker…");
  compile("tsconfig.sw.json");

  for (const path of STATIC_FILES) {
    cpSync(join(ROOT, path), join(OUTPUT, path), { recursive: true });
  }

  fillInServiceWorker();
  console.log(`Built the site in ${relative(process.cwd(), OUTPUT) || "."}${sep}`);
}

/** Runs the TypeScript compiler with one of the project's settings files. */
function compile(projectFile: string): void {
  const compiler = join(ROOT, "node_modules", "typescript", "bin", "tsc");
  execFileSync(process.execPath, [compiler, "--project", join(ROOT, projectFile)], {
    stdio: "inherit",
  });
}

/**
 * Puts the list of site files and a content-based version at the top of the
 * compiled service worker. The version changes whenever any file changes,
 * so installed copies of the app always pick up updates.
 */
function fillInServiceWorker(): void {
  const serviceWorkerPath = join(OUTPUT, "sw.js");
  const siteFiles = listFiles(OUTPUT)
    .map((path) => relative(OUTPUT, path).split(sep).join("/"))
    .filter((path) => path !== "sw.js" && !path.endsWith(".map"))
    // The spare icon set isn't used by the app, so don't download it for offline use.
    .filter((path) => !path.startsWith("assets/icons/alternative/"))
    .sort();

  const hash = createHash("sha256");
  for (const path of siteFiles) {
    hash.update(path);
    hash.update(readFileSync(join(OUTPUT, path)));
  }
  const version = `nasp-scan-${hash.digest("hex").slice(0, 12)}`;

  const header = [
    "// Generated by scripts/build.ts.",
    `const CACHE_VERSION = ${JSON.stringify(version)};`,
    `const APP_FILES = ${JSON.stringify(["./", ...siteFiles], null, 2)};`,
    "",
  ].join("\n");
  writeFileSync(serviceWorkerPath, header + readFileSync(serviceWorkerPath, "utf8"));
}

/** Lists every file under a folder, including subfolders. */
function listFiles(folder: string): string[] {
  return readdirSync(folder, { withFileTypes: true }).flatMap((entry) => {
    const path = join(folder, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  });
}
